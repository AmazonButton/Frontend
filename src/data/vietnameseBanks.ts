export const findBankByBin = (bin: string): VietnameseBank | undefined => {
  return VIETNAMESE_BANKS.find((b) => b.bin === bin);
};

export const findBankByNameOrCode = (keyword: string): VietnameseBank | undefined => {
  const q = keyword.toLowerCase().trim();
  return VIETNAMESE_BANKS.find(
    (b) =>
      b.shortName.toLowerCase() === q ||
      b.code.toLowerCase() === q ||
      b.name.toLowerCase() === q ||
      b.bin === q
  );
};
